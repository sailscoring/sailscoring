/**
 * Sync the course-cards data sets' charts into the app: the captured chart
 * of each club's water that a course is drawn on.
 *
 * Run: pnpm course-cards:sync   (also run automatically by `prebuild`)
 *
 * The pinned release lives in lib/course-cards/dataset-version.txt. Two
 * outputs, mirroring scripts/sync-canonical-logos.ts:
 *
 *   - lib/course-cards/generated/charts.ts — the committed list of the
 *     release's charts and where each sits (the set, its club and event,
 *     the ground the image covers), so which chart covers a course is known
 *     without a network call, in the browser and on the publishing server
 *     alike.
 *   - public/course-cards/<set>/map/<file> — the images, gitignored and
 *     re-fetched at build time; the app fetches a chart on demand from its
 *     own origin, so there is no CORS and no runtime dependency on
 *     courses.sailscoring.ie.
 *
 * Idempotent: if public/course-cards/.version already matches the pin, the
 * download is skipped so repeat builds are fast and offline-friendly.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { setTimeout } from 'node:timers/promises';

import { parseCatalogue } from '@sailscoring/course-cards';

import type { CourseChart } from '../lib/course-cards/types';

const LIB_DIR = join(__dirname, '..', 'lib', 'course-cards');
const VERSION_FILE = join(LIB_DIR, 'dataset-version.txt');
const GENERATED_DIR = join(LIB_DIR, 'generated');
const PUBLIC_DIR = join(__dirname, '..', 'public', 'course-cards');
const VERSION_MARKER = join(PUBLIC_DIR, '.version');
const SITE = 'https://courses.sailscoring.ie';

const FETCH_ATTEMPTS = 3;
const RETRY_BASE_MS = 1000;

function isRetriableStatus(status: number): boolean {
  return status === 408 || status === 429 || status >= 500;
}

function errorSummary(err: unknown): string {
  if (!(err instanceof Error)) return String(err);
  return err.cause instanceof Error ? `${err.message} (${err.cause.message})` : err.message;
}

/** Fetch one file of the release, retrying the failures worth retrying. */
async function fetchText(url: string): Promise<string> {
  let lastError: unknown;
  for (let attempt = 1; attempt <= FETCH_ATTEMPTS; attempt++) {
    if (attempt > 1) {
      const delay = RETRY_BASE_MS * 2 ** (attempt - 2);
      console.log(`Retrying ${url} in ${delay}ms (attempt ${attempt}/${FETCH_ATTEMPTS}): ${errorSummary(lastError)}`);
      await setTimeout(delay);
    }
    let res: Response;
    try {
      res = await fetch(url);
    } catch (err) {
      lastError = err;
      continue;
    }
    if (res.ok) return res.text();
    const err = new Error(`Failed to fetch ${url}: ${res.status} ${res.statusText}`);
    if (!isRetriableStatus(res.status)) throw err;
    lastError = err;
  }
  throw new Error(`Failed to fetch ${url} after ${FETCH_ATTEMPTS} attempts: ${errorSummary(lastError)}`, {
    cause: lastError,
  });
}

/** Fetch one binary file of the release — a set's chart image — with the
 *  same retries. */
async function fetchBytes(url: string): Promise<Uint8Array> {
  let lastError: unknown;
  for (let attempt = 1; attempt <= FETCH_ATTEMPTS; attempt++) {
    if (attempt > 1) {
      const delay = RETRY_BASE_MS * 2 ** (attempt - 2);
      console.log(`Retrying ${url} in ${delay}ms (attempt ${attempt}/${FETCH_ATTEMPTS}): ${errorSummary(lastError)}`);
      await setTimeout(delay);
    }
    let res: Response;
    try {
      res = await fetch(url);
    } catch (err) {
      lastError = err;
      continue;
    }
    if (res.ok) return new Uint8Array(await res.arrayBuffer());
    const err = new Error(`Failed to fetch ${url}: ${res.status} ${res.statusText}`);
    if (!isRetriableStatus(res.status)) throw err;
    lastError = err;
  }
  throw new Error(`Failed to fetch ${url} after ${FETCH_ATTEMPTS} attempts: ${errorSummary(lastError)}`, {
    cause: lastError,
  });
}

function renderChartsModule(version: string, charts: CourseChart[]): string {
  return [
    '// AUTOGENERATED by scripts/sync-course-cards.ts — do not edit by hand.',
    `// Source: ${SITE}/v${version}/index.json`,
    '',
    "import type { CourseChart } from '../types';",
    '',
    `export const COURSE_CARDS_RELEASE = ${JSON.stringify(version)};`,
    '',
    `export const COURSE_CHARTS: CourseChart[] = ${JSON.stringify(charts, null, 2)};`,
    '',
  ].join('\n');
}

async function main() {
  const version = readFileSync(VERSION_FILE, 'utf8').trim();
  if (!/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(`dataset-version.txt must contain MAJOR.MINOR.PATCH, got ${JSON.stringify(version)}`);
  }

  const haveCharts = existsSync(join(GENERATED_DIR, 'charts.ts'));
  const haveFiles = existsSync(VERSION_MARKER) && readFileSync(VERSION_MARKER, 'utf8').trim() === version;
  if (haveCharts && haveFiles) {
    console.log(`course-cards ${version} already in sync — skipping.`);
    return;
  }

  console.log(`Syncing course-cards ${version}…`);
  const catalogue = parseCatalogue(JSON.parse(await fetchText(`${SITE}/v${version}/index.json`)));
  if (catalogue.version !== version) {
    throw new Error(`catalogue says version ${catalogue.version}, pin says ${version}`);
  }

  rmSync(PUBLIC_DIR, { recursive: true, force: true });
  mkdirSync(PUBLIC_DIR, { recursive: true });
  // Everything the renderer has to know about a chart — what it covers, how
  // big it is, who to attribute — travels in the catalogue, so only the
  // image itself is fetched. Sets without one draw on plain ground.
  const charts: CourseChart[] = [];
  for (const set of catalogue.sets) {
    if (!set.map?.placement) continue;
    const png = await fetchBytes(`${SITE}/v${version}/${set.map.background}`);
    const pngPath = join(PUBLIC_DIR, set.map.background);
    mkdirSync(dirname(pngPath), { recursive: true });
    writeFileSync(pngPath, png);
    charts.push({ set: set.path, club: set.club, event: set.event, file: set.map.background, placement: set.map.placement });
  }
  writeFileSync(VERSION_MARKER, `${version}\n`);
  console.log(`Wrote ${charts.length} charts to public/course-cards/.`);

  mkdirSync(GENERATED_DIR, { recursive: true });
  writeFileSync(join(GENERATED_DIR, 'charts.ts'), renderChartsModule(version, charts));
  console.log(`Wrote where they sit to lib/course-cards/generated/charts.ts.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
